let session_id = Math.random().toString(36).substring(7);

async function sendMessage() {
    console.log("sendMessage called");
    const input = document.getElementById("messageInput");
    const chat = document.getElementById("chat");
    const verdictBox = document.getElementById("verdict");

    const message = input.value.trim();
    if (!message) return;

    // ✅ Show user message ONCE
    chat.innerHTML += `<div class="user-msg">🧑 You: ${message}</div>`;
    input.value = "";
    chat.scrollTop = chat.scrollHeight;

    // ✅ Show typing indicator
    const thinkingDiv = document.createElement("div");
    thinkingDiv.id = "thinking";
    thinkingDiv.className = "bot-msg";
    thinkingDiv.innerHTML = "🤖 Bot is analyzing...";
    chat.appendChild(thinkingDiv);
    chat.scrollTop = chat.scrollHeight;

    // ✅ Send to backend
    const res = await fetch("/webhook", {
        method: "POST",
        headers: {
            "Content-Type": "application/json"
        },
        body: JSON.stringify({
            session_id: session_id,
            message: message
        })
    });

    const data = await res.json();

    // ✅ Remove typing indicator
    const thinking = document.getElementById("thinking");
    if (thinking) thinking.remove();

    // ✅ Show bot reply
    chat.innerHTML += `<div class="bot-msg">🤖 Bot: ${data.reply}</div>`;

    // ===== VERDICT + ANALYSIS SYSTEM =====
    if (data.analysis) {
        const risk = data.analysis.risk_score;
        const type = data.analysis.scam_type;
        const flags = data.analysis.red_flags.join(", ");

        let verdictText = "";
        verdictBox.className = "";
        verdictBox.style.display = "block";

        if (risk >= 60) {
            verdictText = "🚨 SCAM DETECTED — DO NOT PROCEED";
            verdictBox.classList.add("verdict-scam");
        } else if (risk >= 30) {
            verdictText = "⚠️ SUSPICIOUS — PROCEED WITH CAUTION";
            verdictBox.classList.add("verdict-suspicious");
        } else {
            verdictText = "✅ SAFE — NO IMMEDIATE THREAT";
            verdictBox.classList.add("verdict-safe");
        }

        verdictBox.innerHTML = `
            <div style="font-size:24px; font-weight:800; margin-bottom:10px;">
                ${verdictText}
            </div>

            <div style="display:flex; gap:20px; flex-wrap:wrap; margin-bottom:12px;">
                <div>📊 <b>Risk Score:</b> ${risk}/100</div>
                <div>🏷️ <b>Type:</b> ${type}</div>
                <div>🚩 <b>Flags:</b> ${flags || "None"}</div>
            </div>

            <div style="margin-bottom:14px;">
                🛡️ <b>Recommended Action:</b><br>
                ${
                    risk >= 60 
                    ? "Immediately stop the conversation. Do NOT share any OTP, PIN, or personal details. Contact your bank using the official number."
                    : risk >= 30 
                    ? "Do not share any sensitive information. Verify the source independently before continuing."
                    : "No immediate action required. Stay alert and cautious."
                }
            </div>

            <button style="padding:10px 16px; border-radius:8px; border:none; cursor:pointer; font-weight:600;"
                onclick="downloadReport(${risk}, '${type}', '${flags}', '${message.replace(/'/g,"")}')">
                📄 Download Full Report
            </button>
        `;
    }

    chat.scrollTop = chat.scrollHeight;
}

// ===== CLEAR CHAT =====
function clearChat() {
    const chat = document.getElementById("chat");
    const verdictBox = document.getElementById("verdict");

    chat.innerHTML = "";
    verdictBox.style.display = "none";

    // Reset backend memory
    fetch("/reset", { method: "POST" });

    // New session
    session_id = Math.random().toString(36).substring(7);
}

// ===== REPORT DOWNLOAD =====
function downloadReport(risk, type, flags, message) {
    const text = `
SCAM ANALYSIS REPORT
-------------------
Message:
${message}

Risk Score: ${risk}/100
Scam Type: ${type}
Red Flags: ${flags}

Generated by AI Scam Detection System
`;

    const blob = new Blob([text], { type: "text/plain" });
    const a = document.createElement("a");
    a.href = URL.createObjectURL(blob);
    a.download = "scam_report.txt";
    a.click();
}